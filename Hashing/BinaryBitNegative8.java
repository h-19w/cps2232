public class BinaryBitNegative8 {
    public static void main(String[]args){
        int x = -8;
        System.out.println("Binary string of -8: " +
                Integer.toBinaryString(x));
        System.out.println("-8 >> 3 is " + (x >> 3));
//right shift
    }
}
