public class UnsignedRightShift {
    public static void main(String[]args){
        System.out.println("-8 >>> 2 is " + (-8 >>> 2));
        System.out.println("8 >>> 2 is " + (8 >>> 2));

        System.out.println("binary string of (-8 >>> 2): " + Integer.toBinaryString (-8 >>> 2));
        System.out.println("binary string of (8 >>> 2): " + Integer.toBinaryString (8 >>> 2));
    }
}
