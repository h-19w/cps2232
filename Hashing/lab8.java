public class lab8 {
    public static void main(String[]args){
        System.out.println("21 >> 2 is " + (21 >> 2));
        System.out.println("-21 >> 2 is " + (-21 >> 2));

        System.out.println("binary string of (21 >>> 2): " + Integer.toBinaryString (21 >>> 2));
        System.out.println("binary string of (-21 >>> 2): " + Integer.toBinaryString (-21 >>> 2));
    }
}
